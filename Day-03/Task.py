import os
from google.colab import userdata
os.environ["GROQ_API_KEY"] = userdata.get("GROQ_API_KEY")   # LangChain reads it from here

from langchain_groq import ChatGroq
llm = ChatGroq(model="openai/gpt-oss-120b", temperature=0.3)

from langchain_core.prompts import ChatPromptTemplate, MessagesPlaceholder
from langchain_core.output_parsers import StrOutputParser

SYSTEM = """ROLE:
You are a friendly assistant for Sweet Crumbs Home Bakery.

FACTS:
Plum cake Rs 500. Chocolate cake Rs 650. Cupcake Rs 80 each.
Orders need 24 hours' notice. All cakes have eggless versions.
Remember the customer's name and order details from the conversation history.

RULES:
Never invent prices, menu items, or bakery policies.
Calculate order totals accurately.
Never promise a delivery time or place.
If something isn't in FACTS, say "I'll check with the owner."
Use conversation history to remember customer details and previous orders.

FORMAT:
Keep responses under 50 words.
Be friendly and concise.
Reply in English or Telugu, matching the customer's language."""

prompt = ChatPromptTemplate.from_messages([
    ("system", SYSTEM),
    MessagesPlaceholder("history"),          # the chat so far goes here
    ("human", "{question}"),
])
chain = prompt | llm | StrOutputParser()

history = []
def ask(question: str) -> str:
    answer = chain.invoke({"history": history, "question": question})
    history.extend([("human", question), ("ai", answer)])
    return answer

